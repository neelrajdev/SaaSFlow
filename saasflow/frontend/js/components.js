export const ROLE_DASHBOARDS = { founder: 'overview.html', consumer: 'my-api.html', finance: 'billing.html' };

export function getRoleDashboard(role) {
  return ROLE_DASHBOARDS[String(role || '').toLowerCase()] || 'overview.html';
}

export function trackPageVisit(pageName) {
  try {
    const path = window.location.pathname.split('/').pop() || pageName;
    const fullUrl = path + window.location.search;
    let stack = JSON.parse(sessionStorage.getItem('sf_nav_history') || '[]');
    if (stack.length === 0 || stack[stack.length - 1] !== fullUrl) {
      stack.push(fullUrl);
      if (stack.length > 25) stack = stack.slice(-25);
      sessionStorage.setItem('sf_nav_history', JSON.stringify(stack));
    }
  } catch (e) {}
}

export function safeGoBack(fallbackUrl = 'overview.html') {
  try {
    let stack = JSON.parse(sessionStorage.getItem('sf_nav_history') || '[]');
    const currentPath = (window.location.pathname.split('/').pop() || '') + window.location.search;
    if (stack.length > 0 && stack[stack.length - 1] === currentPath) stack.pop();

    let target = null;
    while (stack.length > 0) {
      const candidate = stack.pop();
      if (candidate && candidate !== currentPath && !candidate.includes('index.html') && !candidate.includes('access-denied.html')) {
        target = candidate;
        break;
      }
    }
    sessionStorage.setItem('sf_nav_history', JSON.stringify(stack));

    const hasInternalReferrer = document.referrer && document.referrer.startsWith(window.location.origin) &&
      !document.referrer.includes('index.html') && !document.referrer.includes('access-denied.html');

    if (window.history.length > 1 && hasInternalReferrer) { window.history.back(); return; }
    if (target) { window.location.href = target; return; }
  } catch (e) {
    console.warn('[Navigation] safeGoBack error:', e);
  }
  window.location.href = fallbackUrl;
}

export function getNavigationContext({ pageName = '', role = 'founder', title = '', customBreadcrumbs = null, customBack = null }) {
  const dashboardUrl = getRoleDashboard(role);
  const dashboardName = role === 'consumer' ? 'My API' : (role === 'finance' ? 'Billing' : 'Overview');
  if (customBreadcrumbs && customBack !== undefined) {
    return { breadcrumbs: customBreadcrumbs, backButton: customBack, dashboardUrl, dashboardName };
  }

  let breadcrumbs = [], backButton = null;
  const backToOverview = { label: 'Back to Overview', href: 'overview.html' };
  const backToBilling = { label: 'Back to Billing', href: 'billing.html' };
  const backToMyApi = { label: 'Back to My API', href: 'my-api.html' };

  switch (pageName) {
    case 'overview': breadcrumbs = [{ label: 'Overview', active: true }]; break;
    case 'my-api': breadcrumbs = [{ label: 'My API', active: true }]; break;
    case 'billing':
      if (role === 'finance') { breadcrumbs = [{ label: 'Billing', active: true }]; }
      else { breadcrumbs = [{ label: 'Overview', href: 'overview.html' }, { label: 'Billing', active: true }]; backButton = backToOverview; }
      break;
    case 'tenants':
      breadcrumbs = [{ label: 'Overview', href: 'overview.html' }, { label: 'Consumers', active: true }];
      backButton = backToOverview;
      break;
    case 'tenant-detail':
      breadcrumbs = [{ label: 'Overview', href: 'overview.html' }, { label: 'Consumers', href: 'tenants.html' }, { label: title || 'Consumer Detail', active: true, id: 'breadcrumb-current-tenant' }];
      backButton = { label: 'Back to Consumers', href: 'tenants.html' };
      break;
    case 'invoice-detail':
      breadcrumbs = [{ label: 'Billing', href: 'billing.html' }, { label: title || 'Invoice Detail', active: true, id: 'breadcrumb-current-invoice' }];
      backButton = backToBilling;
      break;
    case 'playground':
      breadcrumbs = role === 'consumer' ? [{ label: 'My API', href: 'my-api.html' }, { label: 'Playground', active: true }] : [{ label: 'Overview', href: 'overview.html' }, { label: 'Playground', active: true }];
      backButton = role === 'consumer' ? backToMyApi : backToOverview;
      break;
    case 'plans':
      if (role === 'consumer') { breadcrumbs = [{ label: 'My API', href: 'my-api.html' }, { label: 'Plans', active: true }]; backButton = backToMyApi; }
      else if (role === 'finance') { breadcrumbs = [{ label: 'Billing', href: 'billing.html' }, { label: 'Plans', active: true }]; backButton = backToBilling; }
      else { breadcrumbs = [{ label: 'Overview', href: 'overview.html' }, { label: 'Plans', active: true }]; backButton = backToOverview; }
      break;
    case 'access-denied':
    case '404':
      breadcrumbs = [{ label: 'Dashboard', href: dashboardUrl }, { label: pageName === '404' ? 'Page Not Found' : 'Access Denied', active: true }];
      backButton = { label: 'Back to Dashboard', href: dashboardUrl };
      break;
    default:
      breadcrumbs = [{ label: title || pageName, active: true }];
  }

  if (customBreadcrumbs) breadcrumbs = customBreadcrumbs;
  if (customBack !== undefined) backButton = customBack;
  return { breadcrumbs, backButton, dashboardUrl, dashboardName };
}

export function renderBreadcrumbs(breadcrumbs) {
  if (!breadcrumbs || !Array.isArray(breadcrumbs) || breadcrumbs.length === 0) return '';
  const items = breadcrumbs.map((c, idx) => {
    const isLast = idx === breadcrumbs.length - 1 || c.active;
    return isLast
      ? `<li class="breadcrumb-item active text-muted fw-semibold" aria-current="page" ${c.id ? `id="${c.id}"` : ''}>${c.label}</li>`
      : `<li class="breadcrumb-item"><a href="${c.href || '#'}" class="text-decoration-none" ${c.id ? `id="${c.id}"` : ''}>${c.label}</a></li>`;
  }).join('');
  return `<nav aria-label="breadcrumb" class="breadcrumb-nav"><ol class="breadcrumb" id="global-breadcrumbs-list">${items}</ol></nav>`;
}

export function updateBreadcrumbs(items) {
  const container = document.getElementById('global-breadcrumbs-list');
  if (container && Array.isArray(items)) {
    container.innerHTML = items.map((c, idx) => (idx === items.length - 1 || c.active)
      ? `<li class="breadcrumb-item active text-muted fw-semibold" aria-current="page" ${c.id ? `id="${c.id}"` : ''}>${c.label}</li>`
      : `<li class="breadcrumb-item"><a href="${c.href || '#'}" class="text-decoration-none" ${c.id ? `id="${c.id}"` : ''}>${c.label}</a></li>`
    ).join('');
  }
}

export function renderBackButton(backButton) {
  if (!backButton || !backButton.href) return '';
  return `<button type="button" id="global-back-btn" class="btn btn-sm btn-outline-secondary btn-back-nav" data-fallback="${backButton.href}" title="${backButton.label}" aria-label="${backButton.label}"><span>←</span> <span class="d-none d-md-inline">${backButton.label}</span><span class="d-inline d-md-none">Back</span></button>`;
}

