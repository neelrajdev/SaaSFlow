function setupMobileSidebar() {
  const hamburger = document.getElementById('btn-hamburger');
  const sidebar = document.getElementById('app-sidebar');
  const backdrop = document.getElementById('sidebar-backdrop');
  if (!hamburger || !sidebar || !backdrop) return;

  const openDrawer = () => {
    sidebar.classList.add('show'); backdrop.classList.add('show');
    document.body.classList.add('drawer-open');
    hamburger.setAttribute('aria-expanded', 'true');
    sidebar.querySelector('.sidebar-nav .nav-link')?.focus();
  };
  const closeDrawer = () => {
    sidebar.classList.remove('show'); backdrop.classList.remove('show');
    document.body.classList.remove('drawer-open');
    hamburger.setAttribute('aria-expanded', 'false');
  };

  hamburger.addEventListener('click', () => sidebar.classList.contains('show') ? closeDrawer() : openDrawer());
  backdrop.addEventListener('click', closeDrawer);
  sidebar.querySelectorAll('.sidebar-nav .nav-link').forEach(link => {
    link.addEventListener('click', () => { if (window.innerWidth < 992) closeDrawer(); });
  });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && sidebar.classList.contains('show')) { closeDrawer(); hamburger.focus(); }
  });
}

