export function renderToast({ message, type = 'info', duration = 3500 }) {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    container.setAttribute('aria-live', 'polite');
    container.setAttribute('aria-atomic', 'true');
    document.body.appendChild(container);
  }

  for (const t of container.querySelectorAll('.custom-toast')) {
    const span = t.querySelector('.toast-message');
    if (span && span.textContent.trim() === message.trim()) {
      t.classList.remove('toast-pulse');
      void t.offsetWidth;
      t.classList.add('toast-pulse');
      return;
    }
  }

  const toast = document.createElement('div');
  toast.className = `custom-toast toast-${type}`;
  toast.setAttribute('role', type === 'error' ? 'alert' : 'status');
  const icon = type === 'success' ? SVG_ICONS.check : (type === 'error' ? SVG_ICONS.close : (type === 'warning' ? SVG_ICONS.alert : SVG_ICONS.info));

  toast.innerHTML = `
    <div class="d-flex align-items-center gap-2">
      <span aria-hidden="true" class="d-inline-flex">${icon}</span>
      <span class="small fw-semibold toast-message">${message}</span>
    </div>
    <button type="button" class="btn-close btn-close-sm ms-2" aria-label="Close notification"></button>
  `;

  const dismiss = () => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateX(100%)';
    toast.style.transition = 'all 0.25s ease';
    setTimeout(() => toast.remove(), 250);
  };

  toast.querySelector('.btn-close').addEventListener('click', dismiss);
  container.appendChild(toast);
  setTimeout(dismiss, duration);
}

